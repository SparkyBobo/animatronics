import logging
logger = logging.getLogger(__name__)

CLOCK_INTERVAL = 60.0 / (120 * 24)  # 20.833 ms

class ShowContext(BaseContext):
    """Show execution context."""

    def __init__(self) -> None:
        """Initialize ShowContext."""
        logger.critical("Initialize ShowContext.")

        # The show status is used by many parts of the pipeline to read the clock.
        self.show_status = ShowStatusProcessor()

        # Execution layer
        self.evaluator = ExecutionEvaluator(self.show_status)
        self.executor =  Executor(evaluator=self.evaluator)
        self.execution_processor =  ExecutionProcessor(next=None, executor=self.executor)
        self.execution_policy = ShowClockQueuePolicy(self.show_status)
        self.execution_queue = QueueProcessor(next=self.execution_processor, policy=self.execution_policy)

        # Planning layer
        self._planner_cache = PlanningCache()
        self.planning_processor = PlanningProcessor(next=self.execution_queue, cache=self._planner_cache)
        self.planning_policy = PlanningPolicy(self.show_status)
        self.planning_queue = QueueProcessor(next=self.planning_processor, policy=self.planning_policy)

        # Perrformance message are generated by the diagnostic pipeline
        #self.diagnostic_controller = DiagnosticsController()
        #self.diagnostic_handler = DiagnosticsEventHandler(self.diagnostic_controller)

        # The show running and file manager listen for performance control events
        #self.performance_dispatch.subscribe(self.show_runner)
        #self.performance_dispatch.subscribe(self.file_manager)

        # The show processor dispatches messages to all show elements.
        self.show_dispatcher = ShowDispatcher()

        # Midi control messages from to the show mapping and then the show dispatcher, then planning.
        # Midi data messages go from character to the planning queue to avoid circular loops
        self.midi_show_mapping = ShowMapper(next=self.show_dispatcher)
        self.midi_character_dispatcher = MidiMessageDispatcher()

        # Performance message are read from the midi port and sent to the show mapping and characters.
        self.midi_stream_dispatch = MidiMessageDispatcher(handlers=[MidiMessageLogger(), self.midi_show_mapping, self.midi_character_dispatcher])
        self.midi_stream_reader = MidiStreamReader(next=self.midi_stream_dispatch)
        self.midi_stream_reader.open(MidiSerialPort().device)

        # Performance message are generated by reading midi files and are
        # sent to the planning queue to avoid circular loops
        self.midi_file_reader = MidiFileReader()
        self.show_reader = ShowReader(reader=self.midi_file_reader, next=self.midi_character_dispatcher)
        self.show_dispatcher.subscribe(self.show_reader)

        # Add the stauts after the reader, then add the planning queue.
        self.show_dispatcher.subscribe(self.show_status)
        self.show_dispatcher.subscribe(self.planning_queue)

        # Setup the services that need periodic callbacks
        self.services = [self.midi_stream_reader, self.show_reader]

    def run(self) -> None:
        # The main run loop
        logger.critical("Starting ShowContext...")

        # Reset
        reset_message = PerformanceResetEventMessage(timecode=-1)
        self.show_dispatcher.process(reset_message)

        # Event loop
        while True:
            for svc in self.services:
                result = svc.service()
                if (result == ServiceResult.EXIT):
                    return

                # Send the midi clock if enabled.
                if (self.show_status.is_running and self.show_status.show_clock > 0):
                    now = time.monotonic()
                    if (now >= self.show_status.next_clock_tick):
                        # Track where we want to be.
                        elapsed = now - self.show_status.start_clock
                        timecode = int(elapsed / CLOCK_INTERVAL) + 1
                        #logger.critical(f"now@{now}, next={self.show_status.next_clock_tick}, err={self.show_status.next_clock_tick-now}, timecode={timecode}, clock={self.show_status.show_clock}")
                        self.show_status.next_clock_tick = now + CLOCK_INTERVAL

                        clock_message = PerformanceClockMessage(timecode=timecode)
                        self.show_dispatcher.process(clock_message)

                        # Service the loop
                        #self.show_status.show_clock = timecode
                        #if (self.show_status.show_clock % 100) == 0:
                        #    logger.critical(f"Clock@{now}")



    def add_service(self, service: Service) -> None:
        #logger.info(f"Adding service {service}")
        self.services.append(service)

    def add_behavior(self, behavior: Behavior) -> None:
        #logger.info(f"Adding behavior {behavior}")
        self.planning_processor.subscribe(behavior)
        self.midi_character_dispatcher.subscribe(behavior)

    def add_mapping(self, mapping: MidiMessageProcessor) -> None:
        #logger.info(f"Adding mapping {mapping}")
        self.midi_character_dispatcher.subscribe(mapping)

    @property
    def planner_cache(self) -> DriverValueCache:
        return self._planner_cache    

    @property
    def planner_queue(self) -> PerformanceMessageProcessor:        
        return self.planning_queue



